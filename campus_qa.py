HELP_TEXT = """
================ 使用帮助 ================
直接输入问题，例如：
  · 图书馆几点开门？
  · 食堂几点开饭？
  · 怎么加入社团？
其他指令：
  · help / 帮助  → 显示本帮助
  · list / 列表  → 查看所有可回答的问题
  · 退出 / exit  → 结束程序
==========================================
"""


def find_answer(question: str):
    """根据关键词命中数量和相似度打分，返回 (标准问题, 答案) 或 None"""
    question = question.strip().lower()
    best_score, best_item = 0.0, None

    for keywords, std_q, answer in KNOWLEDGE:
        # 1) 关键词命中：每个命中的关键词记 2 分
        score = sum(2 for kw in keywords if kw in question)
        # 2) 整句相似度（处理换个说法的情况），最高贡献 3 分
        similarity = difflib.SequenceMatcher(None, std_q.lower(), question).ratio()
        score += similarity * 3
        if score > best_score:
            best_score, best_item = score, (std_q, answer)

    # 阈值：至少命中 1 个关键词或有一定相似度
    if best_score >= 2:
        return best_item
    return None


def show_all_questions():
    print("\n--------- 我能回答这些问题 ---------")
    for i, (_, std_q, _) in enumerate(KNOWLEDGE, 1):
        print(f" {i:>2}. {std_q}")
    print("------------------------------------\n")


def main():
    print("=" * 42)
    print("        🏫 欢迎使用校园问答小工具 🏫")
    print("=" * 42)
    print(HELP_TEXT)

    while True:
        try:
            question = input("你：").strip()
        except (EOFError, KeyboardInterrupt):
            print("\n再见，祝你校园生活愉快！👋")
            break

        if not question:
            continue
        if question.lower() in ("exit", "quit", "退出", "再见"):
            print("小助手：再见，祝你校园生活愉快！👋")
            break
        if question.lower() in ("help", "帮助", "?"):
            print(HELP_TEXT)
            continue
        if question.lower() in ("list", "列表", "问题列表"):
            show_all_questions()
            continue

        result = find_answer(question)
        if result:
            std_q, answer = result
            print(f"小助手：{answer}")
            print(f"        （参考问题：{std_q}）\n")
        else:
            print("小助手：抱歉，我还没学会这个问题 😥 输入 list 可以查看我能回答的问题。\n")


if __name__ == "__main__":
    main()
